## 一、一般情況下的聖禮
教會的教義是按邏輯順序發展起來的。當教會建立在猶太教的基礎上時，她肯定了《舊約》中關於上帝的合一和良善的教導，反對了異教徒的多神論和諾斯替主義者（the gnostics）的二元論（dualism）。接著，道成肉身的啓示使教會認識到了基督這一位格中的人神兩性，以及持續引導和激勵著教會的聖靈。這一宣認反過來也蘊含著「三位一體」的教義。在這些事宜明晰後，教會就開始系統地思考聖禮，通過這些聖禮，上帝將祂的所造物與祂自己聯合起來，並與全人類分享道成肉身的果實。當然，早在教會開始思考聖禮之前，大公並使徒所傳的教會就已經在崇拜上帝並舉行聖禮。聖禮的教義來自於教會對自己敬拜生活的自我反思。
《三十九條信綱》的第二十五條有這樣的表述：
> 基督所立的聖事，不獨是基督徒奉教的符號或標記；更是上帝給我們恩惠、善意、確實的憑據、有效的象徵。上帝借此愛我們中間（或作心中），無形地行他的作為，不但活潑有力，更能增進強固我們的信德。[^1]
在《公禱文》的教會問答中則提到聖禮是：
> 聖事，外面可看見的記號，內面不可看見的靈恩。是基督親自設立的，為我們受恩的法子，也為我們受恩的憑據。[^2]
由此，我們瞭解到聖禮是恩典的一種方式: 不獨是一種符號或標記，更是一種有效的象徵。上帝借聖禮給予恩典，聖禮同時也是我們受恩的憑據。這一定義與一些新教的觀點相反，新教的觀點認為聖禮沒有客觀的、實際的效果，而只是無形的恩典的一種標記或象徵。
天主教的觀點則是：聖禮不僅是標記，它也是產生聖禮所指示的恩典的憑據，同時也指示出聖禮所產生的恩典。
以聖洗禮為例，一些新教徒認為受洗僅僅是罪得赦免的標誌，作為對信仰的回應或僅僅是出於上帝的悅納，上帝實際在聖洗禮時就立即將赦免賜給了那些要被拯救的人的靈魂。安立甘公教的觀點是：洗禮主要是上帝用來赦罪、傳遞恩典、開啓新生命，並將新的基督徒融入基督的身體的手段。我們相信「為赦罪設立的獨一洗禮」(尼西亞信經)，而不僅僅是赦罪的標誌——儘管聖禮也是這樣的標誌或法子。所以，聖洗禮不僅象徵著洗去罪，而且也是洗去罪的手段。
聖禮是由人來擔任的聖品施行的，但這些聖品僅是上帝的器皿。首要的動因仍是上帝。聖禮是上帝借由人這一器皿而施行給人的作為。因為聖禮是上帝為首要動因的作為，所以聖禮的效用並不取決於施行者的個人品行。（參見1928年版美國公禱書第607頁，《三十九條信綱》第二十六條）（譯者注：本條的中文翻譯在ACC in China重版的《公禱文》第709頁）同樣，即使施行者或領受者不完全理解聖禮，聖禮也是有效的：事實上，我們永遠無法完全理解聖禮或它們所傳達的恩典。然而，直接或習慣性地拒絕上帝或某種聖禮的恩典，確實會使領受者無法領受該種聖禮的恩典。
對上帝或聖禮恩典的「直接」拒絕包括：例如，有人為了取悅父母而領受聖餐，但在內心卻拒絕相信上帝，或者告訴自己聖餐是迷信的無稽之談。「習慣性地」拒絕上帝或聖禮的恩典，意味著領受者的生命在整體上遠離了上帝和在恩典中成長的可能性。例如，一個人如果一直生活在通姦狀態中，就會習慣性地遠離上帝。儘管他可能不會直接或有意識地拒絕這種恩典，或儘管他可能不認為他領受聖禮是徒勞的，但是他也大體上處於拒絕聖禮恩典的狀態。
簡而言之，除了那些堅決拒絕恩典或那些使自己自絕於恩典的人。在聖禮中，上帝總是，信實、真實並客觀地傳達恩典。恩典總是通過聖禮給予的，但有時這種給予也會遭到拒絕。聖禮有時被比作軌道上的火車:火車必然會到達軌道的盡頭，除非有什麼東西讓火車停下來或脫軌。
當然，除了聖禮之外，還有許多其他的恩典方式。例如，在聖禮之外的祈禱也是一種恩典。這些其他的恩典方式與聖禮不同（其中許多被稱為「類聖禮」，即sacramentals；這個詞有點令人費解，是與「聖禮」，即sacraments相對的）。聖禮客觀地將恩典傳達給所有不主動拒絕它的人。聖禮更多地取決於領受者的主觀意圖、虔誠和努力。例如，用聖水祝福自己的人，客觀上並不會因此變得更好或更神聖。如果某人確實因自己的行為而得到了恩典，那麼這個恩典就來自他做這個行為時所帶入的虔敬的主觀意圖——例如，來自於在行某件事時所激起的受洗時的回憶。
聖禮（sacraments）和類聖禮（sacramentals）之間的區別有時用兩個拉丁短句來表示。聖禮（sacraments）所傳達的恩典是「因功生效」的（拉丁語：ex opere operato，即通過聖工所產生的功效——作為所做聖工的客觀功效）；類聖禮（sacramentals）所傳達的恩典則是「因行生效」（拉丁語：ex operando operis，即在做某種行為的過程中所帶有的某項主觀因素的功效）。
因此，如上文中所引用的，即「聖事，外面可看見的記號，內面不可看見的靈恩。是基督親自設立的，為我們受恩的法子，也為我們受恩的憑據。」 如果一件聖禮是「有效的」，那它就是真實且生效了的。聖禮的「有效」必須具備幾個要素：合宜的形式（所使用的用語）、質料（所做的事情或可見的行為或使用的材料）、聖品（舉行聖禮的人）和意圖（聖品人員的意圖或目的）。正確的意圖通常意味著想要做基督或教會希望我們在聖禮中所行的事，而不是打算做任何與之相矛盾的事情。在受洗之前，任何人都不能接受任何種類的其他聖禮。為了使聖禮有良好的效果，大多數聖禮也要有合適的領受者。
除了有效性之外，神學家們還談到了聖禮的合規性（regularity）和不合規性（irregularity）。不合規的聖禮是有效的（也就是說，它確實提供了恩典），例如，被罷免了聖品的司祭不應該主持告解聖禮或進行赦罪（除非是對處於極端狀態的人）。然而，如果被罷免的司祭這樣做了，聖禮的恩典也同樣被給予了。
聖禮共有七件：聖洗（Holy Baptism）、堅振（Confirmation）, 告解（Penance）, 聖餐（the Holy Eucharist）, 婚姻（Holy Matrimony）, 聖品（Holy Orders）, 終傅（Unction of the Sick）。
《三十九條信綱》的第二十五條提到：我主基督在福音中，所設立的聖禮，有兩件：即聖洗禮和主的聖餐。通俗所稱的五聖禮，毫無外面可見的記號，或上帝所命定的禮儀。《教會問答》中也提到了「基督親自設立的聖事只有兩件，為凡要得救的人，應該領受的」（參見1928年版美國公禱書第581頁）（譯者注：該引用的中文翻譯在ACC in China重版的《公禱文》第644頁）。大多數安立甘公教的神學家對這兩件聖禮的解釋如下：在東方和西方教會中，通常有七件聖禮。其中兩個是基督親自設立的，作為得救的必要手段，即聖洗禮和聖餐禮。至於其他的聖禮，儘管其中一些通常是有用和重要的，並且另一些可能是特別的且不具有普遍性和必要性，但對於得救來說則不是普遍必要的。例如，所有的基督徒都應受堅振（Confirmation）。儘管受堅振不是絕對必要的，但堅振通常是有用和重要的（例如，在美國的第一位主教塞繆爾·西伯里（Samuel Seabury）被祝聖之前，美國人除非前往英國，否則無法領受堅振，但這些人仍然可以獲准參加聖餐，並借此得救）。堅振就是一種普適但不絕對必要的聖禮。同樣的，如果一個人蒙聖召要成為聖品或步入婚姻，那麼為了此人的得救就必須接受相應的聖禮。但並不是每個人都會受到這樣的呼召，所以婚姻（Holy Matrimony）和聖品（Holy Orders）這兩件聖禮通常不是得救的必要條件，只是在某些情況下尤為必要。
三件神印聖禮（sacraments of character）分別是：聖洗（Holy Baptism）、堅振（Confirmation）和聖品（Holy Orders），這些聖禮賦予靈魂一種永久的、不可磨滅的神印或印記。這三件聖禮不能重復領受，重復領受神印聖禮是一種嚴重的褻瀆。如果對先前執行的某件此類聖禮的有效性有疑問，則可以「有條件的」舉行此類聖禮，即「某人某名，如果你未曾受洗，我就以某某的名義給你施洗」（原文：if thou art not already baptized, I baptize thee in the Name of etc.）
## 二、特殊情況下的聖禮
### A、施洗（Baptism）
- 形式：我奉聖父、聖子、聖靈的名給你施洗（I baptize thee in t he name of the Father, and of Son, and of the Holy Ghost）。
- 質料：注水禮或浸水禮。
- 主禮：任何基督徒都可以施洗，也許任何人都可以。
- 領受者：如果是一個意識清楚並有理性的成年人，其至少應該是對基督作為上主和救主有最起碼的信心的人。如果一個人還沒有達到理性的年齡，他或她應該由保證人（sponsors）承諾以後在信仰上教導他。
施洗賦予靈魂一種神印（sacramental character）（就像封蠟上的封印），它不能被摧毀或移除。一旦受洗，則永遠受洗。因此，施洗是不能重復領受的。通過上帝的洗禮:1、赦免或寬恕所有源自原罪和受洗之前本罪（personal sin）的罪過和懲罰;2、使我們成為教會的一員，這樣我們就能領受其他聖禮，在我們的餘生中幫助我們。
聖經中幾乎沒有提到嬰兒洗禮（infant baptism），儘管聖經確實提到了一家的人在沒有排除嬰兒和孩子的情況下受洗(《使徒行傳》16:14- 15,16:33;《哥林多前書》1:16)。嬰兒洗禮（infant baptism）使我們融入教會這個新的以色列，就像割禮使男孩在8天大的時候融入舊的以色列。嬰兒在產生本罪（personal sin）前就已沾染了原罪，因此他們需要盡快獲得洗禮的恩典。東方神學強調死亡是原罪的果實（fruit），並將聖禮稱為「不死之藥」（the medicine of immortality）。嬰兒也不能免於死亡。因此，在公元16世紀開始被少數新教徒拒絕之前，嬰兒洗禮（infant baptism）一直是教會普遍的且從未間斷的實踐。早在公元2世紀和3世紀的作家們，如聖愛任紐（St.Irenaeus）、奧利金（Origen）和特土良（Tertullian），就提到嬰兒洗禮是一種古老的且具有使徒遺傳（apostolic）的實踐。路德宗（Lutherans）、衛理公會（循道宗）（Methodists）、長老宗（Presbyterians）以及其他新教教徒都實行嬰兒洗禮。一些主要的改教家認為嬰兒洗禮特別符合「得救本乎恩」（salvation by grace）的教義:嬰兒顯然沒有為受洗而去行善功(merit)或工作（work）。
一個尚未達到理智年齡的兒童由教父母（godparents'）或保證人（sponsors）領來受洗。傳統上，是由兩個與孩子性別相同的教父母和一個與孩子性別不同的教父母領來。所有教父母都應已經受洗且應是虔誠的基督徒。所有的教父母都必須理解並同意他們把孩子帶到主教那裡領洗時所做的承諾（1928年版美國公禱書第277頁）（譯者注：本頁的中文翻譯可查閱ACC in China重版的《公禱文》第336頁），這意味著他們將幫助這個孩子成長為大公教會的一員，並將在該教會中瞭解並領受堅振（Confirmation）。最理想的是，至少有一位教父母應該是這個孩子成長所在教區中定期領受聖餐的人。
對於年幼的兒童，父母和教父母會將自己的信仰歸給這個孩子。這種歸給類似於基督用醫治或寬恕某個孩子或某個奴隸這樣的慣常做法來回應其父母或主人的信仰。雖然基督經常用醫治和赦罪來直接回應信心的表現，但福音書中沒有提到這些被醫治或被赦免的兒童和奴隸對應的父母和主人的信仰（見《馬太福音》8:5-13；15:22-28；《馬可福音》2:3-12；5:22-24，35-42；7:25-30；《路加福音》7:1-10）。
一個已經受洗的孩子，如果還沒有到理性的年齡，就處於一種恩典且不會犯下嚴重的罪行的狀態。在這種狀態下去世的孩子會毫無疑問地進入天堂。
### B、堅振（Confirmation）
- 形式：聖靈七恩禱文（Prayer for the seven-fold gift of the Holy Ghost）
- 質料：按手或用聖油膏塗，又或兩者兼有。
- 主禮：一名主教
在堅振聖禮中，一名已經達到理性年齡的已受洗者，會對其在教父母（godparents'）或保證人（sponsors）於其領洗時所作的承諾做出確信，該確信也會使此人獲得進一步的恩典以幫助其過一名基督徒的生活。
在東正教會中，司祭可以用經過主教祝聖的膏油來舉行堅振，羅馬天主教會中有時也會如此。在東正教及東儀天主教的禮儀中，堅振是在受洗後立即進行的，並且被稱為「聖膏」（Chrismation）。安立甘宗僅將堅振的主禮人恰如其分地限於主教。許多安立甘宗的洗禮形式確實也包含領洗人在受洗之後接受聖油膏塗的環節，但這個膏塗的環節並不能替代之後的堅振。
### C、告解（Penance）
- 形式和質料：已受洗的基督徒對自身的一些過犯所做的懺悔，隨後由司祭進行赦免。
- 主禮：一名司祭或主教
這一聖禮可以重復無數次，而且對人大有幫助，既可以幫助懺悔者悔罪，也有助於這個人聽取司祭的忠告和建議。在特利騰會議（the Council of Trent）之後的羅馬天主教中，所有人都被要求承認所有其所犯的重罪，無論是數量還是種類(次數)。安立甘宗對於這個聖禮的實踐較此更為寬松，但一個好的教友應該在其每年的復活節聖餐之前的一年時間里至少舉行一次告解聖禮。
該聖禮在《公禱書》中提到了兩次(88頁和313頁)。《公禱書》中並沒有對該聖禮的實際管理提供形式，因為它本質上是私人的聖事，而不是「公禱」。私下和公開的懺悔和赦免是基督賦予其使徒(以及擁有使徒統緒的主教和司祭們)捆綁和赦罪的權柄的理所當然的結論——《馬太福音》16:19、18:18，《約翰福音》20:23。《雅各書》5：16提到了懺悔的作用:「彼此承認自己的過失，彼此為對方祈禱，這樣你們就可以得醫治。」 然而，相互懺悔的行為也存在明顯的風險，因此教會採取了相應的防範措施: 第一，把聖事的主禮限制在那些受過教會訓練並獲得教會許可的人(即司祭和主教，在各種緊急情況下，也僅有擁有緊急授權和牧領職責的司祭或主教可以主禮);第二、懺悔保密制（the seal of confession）。
一段真切且確實的懺悔中所傳遞的所有信息在教會法系中均享有特許保密權，並且根據教會法規，這些信息都屬於懺悔保密制（the seal of confession）的保護範圍。懺悔保密制是絕對的，這意味著若未經懺悔者的明確事先許可，司祭不得以任何方式使用懺悔中所傳達的信息。例如，如果懺悔者承認他恨這位司祭，那麼這位司祭不得在懺悔之後以任何方式改變他對這名懺悔者的行為。或者，如果懺悔者承認他的幫派將在回家的路上搶劫和毆打這名司祭，那麼該司祭也不得改變其慣常路線。或者，如果懺悔者承認犯下了臭名昭著的謀殺罪，司祭也不得將此通知任何人。只有在懺悔者拒絕賠還、拒絕為先前的罪行自首、或拒絕承諾在未來不作惡的情況下，司祭才可以在告解聖禮上拒絕其懺悔和對其的赦免。懺悔保密制具有絕對性的原因很簡單:必須盡一切可能防止那些需要聖禮的人將聖禮視為可憎或令人反感的事情。
在安立甘公教會（同時羅馬天主教中也是如此）中，違反懺悔保密制（the seal of confession）的司祭將被自動開除教籍並被免職。違反懺悔保密制（the seal of confession）的平信徒，例如洩露了偷聽到的東西，也將被開除教籍。
### D、聖餐（Eucharist）
- 形式：至少使用主在最後的晚餐中所確立的話語（「這是我的身體……這是我的血……」），也可能兼有一套包含著四種行為的流程：向上帝供獻並重新領受餅和酒，祝謝（giving thanks），祝聖（blessing），然後在聖餐中分發。
- 質料：純小麥聖餐餅和天然發酵的葡萄酒。
- 主禮：一名司祭或一名主教
聖餐（Eucharist）是最大的聖事，因為在這聖事里，上帝不僅賜恩給人，而且在酒和餅的表象之下，上帝自身也真實臨在（Real Presence）。安立甘公教會並沒有定義這種真實臨在的模式。安立甘宗教友可接受或不接受各種解釋真實臨在這一事實的現代理論。其中一個理論是變體論（Transubstantiation），這一理論是羅馬天主教友必須認信的信理。變體論是這樣的一條信理：應相信酒和餅的質體轉變為了基督的血和肉，原來的酒和餅只在偶性（accidents）[^3]和物質性（outward effects）上保持不變（另一方面，《三十九條信綱》拒絕承認變體論【見《三十九條信綱》第28條】[^4]。羅馬天主教必然只提及該理論在《三十九條信綱》撰寫之前的版本，而不提及該理論的現代版本，因為後者可能為安立甘宗所相信）。路德宗（Lutherans）則認信同體論（Consubstantiation），即在聖餐儀式和聖餐禮舉行的過程中，基督的身體和血的物質與餅和酒的物質同時存在，就像把鐵放入火中時，熱量與鐵的物質同時存在一樣。教會的教父們則使用諸如「轉實化」（Transelementation）這樣的術語，雖然沒有現代的「變體」（Transubstantiation）那麼精確和明確，但這個詞意味著酒和餅的物質性發生了變化，而不僅僅是酒和餅的意思或意義的改變。這種模糊的理論現在被安立甘宗所普遍接受，但也不排除一些信友在個人層面上持有更精確、更明確的觀點。例如，《謙恭近主文》（the Prayer of Humble Access）[^5]中的寫實語言就為真實臨在這一理論提供了支撐。
聖餐（Eucharist）也是一種獻祭。這是一種「稱頌主感謝主的祭」[^6]。基督只這一次地在十字架上受死，作為世人的贖罪祭:「為滿足完全的贖罪祭，就是為古今眾人的罪獻的」[^7]。因此，聖餐並不是一個新的或是不同於基督在十字架上完成的獻祭，而是如同基督在十字架上那僅有一次的獻祭一般。更確切地說，聖餐是和在十字架上的受難的基督是一樣的祭物，不是新獻的，而是代表了基督的這次獻祭。至於十字架上這次獨一的獻祭是如何在不被重復的情況下通過聖餐呈現出來，則仍是一個奧秘，但教會一直意識到並承認聖餐對於此次獻祭的代表作用。
領受聖餐的人必須受洗（baptized）。在安立甘公教會中，信友在領受聖餐前也需領受堅振（Confirmation）或「已預備甘受而未受（堅振）者，則亦可領聖餐」[^8]。領受聖餐的人也處於一種領受恩典的狀態，即「與人親愛和睦，立志自新，從今以後，遵上帝的命令，行上帝的聖道」[^9]。至關重要的是，不能粗心大意地領受聖餐，因為「無論何人不按理吃主的餅、喝主的杯，就是干犯主的身、主的血了……因為人吃喝，若不分辨是主的身體，就是吃喝自己的罪」（哥林多前書11:27,29）。
所以，在聖餐這一聖事上随意而行，並非仁慈之舉。
### E、婚姻（Matrimony）
- 形式:以交換婚誓（該誓言通常以戒指或牽手為象徵）的方式將其他所有人排除在外，併為上帝設立婚姻的目的（彼此相恤相伴、生養孩童）而終身不渝。
- 質料: 一男和一女。
- 主禮：如上所述的一男和一女。
司祭為教會祝福並見證婚禮，但這對夫婦兩人都是該聖禮的主禮。婚姻確立了一種神印（sacramental character），但這種神印是以一方死亡而告終的。
因為這對夫婦兩人都是該聖禮的主禮，而一個有效並具有神印的婚姻要求夫婦雙方都是真正自由並完全知情且同意的基督徒。任何可能存在的有礙於或限制他們二人基於此點，在上帝面前締結一個彼此相恤相伴、生養孩童，並且終身且不可分割的聯合的婚姻的因素，都將成為使婚姻失去聖禮的功效。
這類使婚姻失去聖禮功效的因素可例舉如下：雙方任意一人不是已受洗且具有信仰的基督徒；沒有生養孩子的意圖(因為在可行的前提下，這是婚姻的一個重要組成部分)；認為婚姻不是絕對且通常不可分割的；存在無論是身體、經濟還是道德上的胁迫、強迫、威脅；一份預設有如果婚姻「無法維持下去」就存在離婚可能性的婚前協議；精神錯亂、極度不成熟或任何使理性、知情的選擇不可能發生的因素； 隱瞞了可能改變對方自由選擇的重要個人信息。如果存在這樣的因素，教會可以宣佈前一段婚姻在聖禮上無效，如此也會允許雙方在教會內另覓良緣。如果沒有基於以上情況的婚姻廢除，教會將不會見證或祝福一個已經在民事上離婚的人的婚姻，因為聖經上說「如果有人休妻，另娶別人，就是犯通姦罪。女人如果離棄丈夫，另嫁別人，也是犯通姦罪」（《馬太福音》10:11-12）。
同時《馬太福音》中的這段經文似乎提出了一種例外:「凡休妻另娶的，若不是為淫亂的緣故，就是犯姦淫了」 (《馬太福音》19:9) 。教會據此認為自己被授予了廢止婚姻的權柄。也就是說，如果先前的婚姻本身是不正當的(該段經文中的「淫亂」fornication，希臘語porneia，意思是「不正當的性行為」)，因此維持該婚姻是錯誤的，那麼教會就可以允許雙方當事人分開，該段婚姻被廢止，並允許雙方另覓良緣或步入第一段正當的婚姻。《馬太福音》的這段經文並沒有改變教會關於有效的婚姻聖禮絕對不可分割性的教導。也就是說，「有效的婚姻聖禮是不可分割的」的這一規則不存在例外。
民事婚姻(由國家承認和管理的婚姻)和自然婚姻(一個男人和一個女人為了婚姻的自然目的——生育和撫養孩子以及相互支持和安慰——而結成的排他性的結合) 都可能以宣告無效、分居或離婚告終；婚姻聖禮可能因宣告無效或天人兩隔而告終，但不會因離婚而告終。也就是說，如果聖禮的紐帶曾經存在，那麼該紐帶則永久存在，除非其中一方死亡。
由於我們的世界並不普遍認為婚姻是不可分割的，因此，現在若是在清晰和明確地教導婚姻的永續性的教會以外訂立的婚姻，幾乎都不具有聖禮性。這樣的婚姻可能是真正的自然婚姻，但並沒有上升到聖禮的水平，也沒有給予聖禮的恩典。
東正教的一個嚴重瑰疵是對離婚和再婚的看法過於鬆懈。各東正教會都將離婚視為一種罪，並會絕罰再婚者，但通常也會在該人懺悔一段時間後又重新允許其領受聖餐。
東正教實際上允許最多三次婚姻，因此他們似乎既對其承認的罪視而不見，也否認了聖禮關係的永續性。東正教認為，《馬太福音》19：9中實際上允許「有效的婚姻聖禮是不可分割的」這一規則可以存在例外，這就使《馬可福音》第10章與《馬太福音》的教義對立了起來。而西方教會的解釋則略勝一籌，因為西方教會對此的解釋調和了著兩段經文。
教會對婚姻聖禮的廢止並不影響所生養兒童的合法性，因為合法性屬於法律範疇，而不是聖禮範疇。國家制定的法律規範了合法性，在美國和大多數國家，現行的國家法律並未將教會對婚姻的廢止納入其中。安立甘公教會的法規明確反對「可因婚姻無效而藉此影響其婚生子女合法性」的觀點。簡而言之，有效的民事婚姻足以保證該段婚姻及其婚生子女的合法性。教會對婚姻的宣告無效只表明前一次既成的婚姻不是聖禮，卻不會妨礙其在這之後於教會中後續的婚姻。
由於動機不良或缺乏客觀自由而在聖禮上被宣告無效的婚姻，若其動機隨後得到糾正或在雙方充分自由的情況下獲得了同意，則仍可以被教會宣告為有效。如果婚姻因其中一方未受洗而無效，則在未受洗的一方受洗時便會使婚姻聖禮生效，屆時教會也會祝福這一結合。
### F、聖品/聖秩（Ordination或Holy Orders）
- 形式:為有志於聖品或聖工的人祈求聖靈恩賜的禱文。
- 質料: 一名男性基督徒。
- 主禮：僅限主教才能主禮。
聖品由三部分組成：執事的任命、司祭的按立、主教的祝聖。僅有主教擁有完備的聖秩，該聖秩有一部分是主教與次一級的執事和司祭這些教會事工共享的。教會中的其他職位，如修士（canon）、教務長（dean）、執事長（archdeacon）或大主教（archbishop），是由選舉或任命產生的，本身不是聖品。
聖品是歷史性的聖禮，是教會組織和聖禮結構的傳遞，也是基督穿越時空的臨在。基督對使徒的揀選和任命則是對基於源自使徒的統緒而產生的聖品的支撐，他授予門徒們權柄，由最初的教會揀選執事，用馬提亞（St. Matthias）取代猶大（Judas），並將使徒職位擴展到保羅（Paul）和巴拿巴（Barnabas），又由保羅擴展到提摩太（Timothy）和提多（Titus）。在所有這些方面，我們看到基督的事工以具體的人為載體，薪火相傳地在時間上延伸，教會將其理解為三重事工（the three-fold ministry）。
從本質上講，當一名主教被祝聖(在次一級聖品中則是司祭和執事受按立)，並不是為了做這做那，也不是為了履行特定的職能或工作，而是為了成為基督的聖像或形象。在聖壇上的主教或司祭對於作為基督的淨配的教會而言，是基督的聖禮代表。由此可見，使徒教團（Apostolic Orders）是男性位格的，因為女人不能成為新郎的形象。在聖經中，上帝以婚姻的方式顯明祂與祂子民的關係。如果認為這些術語是錯誤的，或者可以用另一組形象和隱喻來代替，那麼就是認為聖經啓示的具體術語是錯誤的或不充分的，應該被取代，或者至少要從根本上進行改變和補充。雖然這樣的論點可以並已經被提出，但這是一個反對聖經和傳統基督教的論點。因此，這一論點也被使徒所傳的教會所普遍拒絕。值得注意的是，堅定的女權主義神學家通常最終會落入完全拒絕基督教的窠臼，而不是簡單地提出改革她。
主教擁有完備的聖秩，是所有聖禮的適當司祭。主教是教區的首席司祭、牧者和教師。教區的首席主教稱為正權主教（the ordinary），在特定的地理區域管理和領導整個教區。只有主教才能任命其他聖品人員。在安立甘宗的傳統中，只有主教才能主禮堅振（Confirmation）。某些祝福通常也專由主教進行降福，如對墋地的祝福或祭壇、教堂或聖盃的祝聖。主教也是他的聖品人員的首席司祭。有權接替正權主教（the ordinary）的協理主教被稱為助理主教（Coadujator Bishop），一般來說，無權接替正權主教的協理主教被稱為輔佐主教（Suffragan Bishop）。
由於主教不可能一直在其教區的任何地方，他會將自己的一些權力和職能委託給次一級的聖品人員。司祭牧師可以在獲得主教授權的情況下，或憑藉主教設立或以其他方式正式任命的職位，進行施洗、堅振、聽取懺悔、見證和祝福婚姻、為病人塗油、埋葬死者、提供諮詢、指導、勸誡和講道。
執事負責協助司祭和主教。尤其是在聖餐中閲讀福音和管理聖盃。執事也可以在獲得主教許可的情況下進行講道。在沒有主教或司祭的情況下，執事也可以施洗和埋葬死者，在某些地方，執事也可以見證婚姻，但不能為婚姻祝福。執事們古老而恰當地協助高級聖品人員救濟窮人和管理教區。自古以來，執事在救濟窮人和管理教區的工作中恰如其分地協助高級聖品人員。

